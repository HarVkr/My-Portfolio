#!/usr/bin/env python3
"""One-time asset generator: bakes SVG stroke contours for "Hello."
from the real Dancing Script glyphs (wght 500) so the intro can draw
them stroke-by-stroke with stroke-dasharray/dashoffset."""

from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.transformPen import TransformPen
import uharfbuzz as hb

SRC = "/tmp/fontwork/DancingScript-VF.ttf"
OUT = "/app/frontend/src/data/helloPaths.js"
WEIGHT = 500
TEXT = "Hello."
SIZE = 240.0
PAD = 26.0

font = TTFont(SRC)
instantiateVariableFont(font, {"wght": WEIGHT}, inplace=True)
upem = font["head"].unitsPerEm
glyph_order = font.getGlyphOrder()
glyph_set = font.getGlyphSet()

inst = "/tmp/fontwork/instanced.ttf"
font.save(inst)

blob = hb.Blob.from_file_path(inst)
face = hb.Face(blob)
hbfont = hb.Font(face)
hbfont.scale = (upem, upem)
buf = hb.Buffer()
buf.add_str(TEXT)
buf.guess_segment_properties()
hb.shape(hbfont, buf, {"kern": True, "liga": True})

placed = []
x = 0
for info, pos in zip(buf.glyph_infos, buf.glyph_positions):
    placed.append((glyph_order[info.codepoint], x + pos.x_offset, pos.y_offset))
    x += pos.x_advance

bpen = BoundsPen(glyph_set)
for name, gx, gy in placed:
    glyph_set[name].draw(TransformPen(bpen, (1, 0, 0, 1, gx, gy)))
minx, miny, maxx, maxy = bpen.bounds

s = SIZE / upem
T = (s, 0, 0, -s, -minx * s + PAD, maxy * s + PAD)
W = (maxx - minx) * s + 2 * PAD
H = (maxy - miny) * s + 2 * PAD


def fmt(v):
    r = round(float(v), 2)
    return str(int(r)) if abs(r - int(r)) < 1e-9 else f"{r:.2f}"


contours = []
for name, gx, gy in placed:
    spen = SVGPathPen(glyph_set, ntos=fmt)
    # final transform: scale to px, flip y, translate glyph to its shaped position
    T = (s, 0, 0, -s, s * gx - minx * s + PAD, -s * gy + maxy * s + PAD)
    glyph_set[name].draw(TransformPen(spen, T))
    d = spen.getCommands()
    if not d:
        continue
    for part in d.split("M"):
        part = part.strip()
        if part:
            contours.append("M" + part)

lines = ",\n".join(f'  "{c}"' for c in contours)
js = (
    "// AUTO-GENERATED by scripts/generate_hello_paths.py - do not edit by hand.\n"
    f"// Source: Dancing Script (OFL), instanced at wght {WEIGHT}, glyphs for \"{TEXT}\".\n"
    f'export const HELLO_VIEWBOX = "0 0 {fmt(W)} {fmt(H)}";\n'
    "export const HELLO_CONTOURS = [\n"
    f"{lines}\n"
    "];\n"
    "export default HELLO_CONTOURS;\n"
)
with open(OUT, "w") as f:
    f.write(js)

print(f"viewBox: 0 0 {W:.1f} {H:.1f} | contours: {len(contours)}")
for c in contours:
    print(f"  - {len(c):5d} chars | {c[:72]}")
